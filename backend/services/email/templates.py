def welcome_email(
    *,
    display_name: Optional[str],
    promo_code: str,
    referral_code: str,
    app_url: str,
    unsubscribe_url: str,
    postal_address: str,
) -> tuple[str, str, str]:
    """The email a new free signup gets: what Rook is, their discount code, and
    their own referral code.

    PROMOTIONAL. Its primary purpose is to sell a subscription, so it carries the
    unsubscribe link and the postal address.
    """
    welcome_pct = REFERRAL_PROGRAM["welcome_percent_off"]
    referred_pct = REFERRAL_PROGRAM["referred_percent_off"]
    per_referral = REFERRAL_PROGRAM["referrer_percent_off_per_referral"]
    cap = REFERRAL_PROGRAM["referrer_percent_off_cap"]
    standard_monthly = TIER_LIMITS["standard"]["price_monthly_usd"]

    name = _greeting_name(display_name)
    subject = f"Welcome to Rook — here is {welcome_pct}% off your first month"
    preheader = (
        f"Your code is {promo_code}. It takes {welcome_pct}% off your first "
        f"month on any monthly plan."
    )

    body = (
        f'<tr><td style="padding:8px 32px 4px 32px;font-family:{_FONT};">'
        + _paragraph(f"Hi {_esc(name)},")
        + _paragraph(
            "Thanks for signing up. Your free account is ready to use right now."
        )
        + _paragraph(_esc(_WHAT_ROOK_IS))
        + _paragraph(
            f"When you are ready to upgrade, this code takes "
            f"<strong>{welcome_pct}% off your first month</strong>. Standard is "
            f"${standard_monthly} a month, and the code works on any monthly "
            f"plan. Enter it at checkout."
        )
        + _code_block(promo_code, "Your first-month discount code")
        + _button(app_url, "Open Rook")
        + _paragraph(
            f"You also have your own referral code. Anyone who uses it gets "
            f"<strong>{referred_pct}% off their first month</strong>, and every "
            f"person who does adds <strong>{per_referral}% off your own monthly "
            f"bill</strong> — up to {cap}%, for as long as you stay subscribed."
        )
        + _code_block(referral_code, "Your referral code")
        + "</td></tr>"
    )

    html_body = _document(
        preheader=preheader,
        body_rows=body,
        footer_row=_promotional_footer(
            app_url=app_url,
            unsubscribe_url=unsubscribe_url,
            postal_address=postal_address,
        ),
    )

    text = (
        f"Hi {name},\n\n"
        "Thanks for signing up. Your free account is ready to use right now.\n\n"
        f"{_WHAT_ROOK_IS}\n\n"
        f"When you are ready to upgrade, this code takes {welcome_pct}% off your "
        f"first month. Standard is ${standard_monthly} a month, and the code "
        "works on any monthly plan. Enter it at checkout.\n\n"
        f"  Your first-month discount code:  {promo_code}\n\n"
        f"Open Rook: {app_url}\n\n"
        f"You also have your own referral code. Anyone who uses it gets "
        f"{referred_pct}% off their first month, and every person who does adds "
        f"{per_referral}% off your own monthly bill - up to {cap}%, for as long "
        "as you stay subscribed.\n\n"
        f"  Your referral code:  {referral_code}\n"
        + _text_footer(
            app_url=app_url,
            unsubscribe_url=unsubscribe_url,
            postal_address=postal_address,
        )
    )
    return subject, html_body, text


def referral_reward_email(
    *,
    display_name: Optional[str],
    new_total_percent: int,
    referral_count: int,
    app_url: str,
    unsubscribe_url: str,
    postal_address: str,
) -> tuple[str, str, str]:
    """The email a REFERRER gets when someone subscribes with their code.

    WHAT THIS MESSAGE DELIBERATELY DOES NOT CONTAIN: any identifying detail about
    the person who redeemed the code — no name, no email address, no signup date.
    The referrer learns only their own new total and their own count. Same rule
    as backend/routers/feedback.py, which files a report under the user's opaque
    id and never their address: user PII does not leave the app, and here it
    would leave to a THIRD PARTY who happens to know the redeemer.

    PROMOTIONAL. Carries the unsubscribe link and the postal address.
    """
    per_referral = REFERRAL_PROGRAM["referrer_percent_off_per_referral"]
    cap = REFERRAL_PROGRAM["referrer_percent_off_cap"]

    name = _greeting_name(display_name)
    friends = "referral" if referral_count == 1 else "referrals"
    subject = f"Your Rook discount is now {new_total_percent}% off"
    preheader = (
        f"Someone subscribed with your referral code. You are now at "
        f"{new_total_percent}% off every month."
    )

    if new_total_percent >= cap:
        next_step = (
            f"That is the maximum — {cap}% is as high as the referral discount "
            "goes."
        )
    else:
        next_step = (
            f"Each additional referral adds another {per_referral}%, up to {cap}%."
        )

    body = (
        f'<tr><td style="padding:8px 32px 4px 32px;font-family:{_FONT};">'
        + _paragraph(f"Hi {_esc(name)},")
        + _paragraph(
            "Someone just subscribed using your referral code. Your discount has "
            "gone up."
        )
        + _code_block(f"{new_total_percent}% off", "Your new monthly discount")
        + _paragraph(
            f"That is {referral_count} confirmed {friends}. {_esc(next_step)} "
            "The discount applies to every monthly bill for as long as you stay "
            "subscribed, and it is applied automatically — there is nothing to "
            "enter."
        )
        + _button(f"{app_url.rstrip('/')}/account", "View your account")
        + "</td></tr>"
    )

    html_body = _document(
        preheader=preheader,
        body_rows=body,
        footer_row=_promotional_footer(
            app_url=app_url,
            unsubscribe_url=unsubscribe_url,
            postal_address=postal_address,
        ),
    )

    text = (
        f"Hi {name},\n\n"
        "Someone just subscribed using your referral code. Your discount has "
        "gone up.\n\n"
        f"  Your new monthly discount:  {new_total_percent}% off\n\n"
        f"That is {referral_count} confirmed {friends}. {next_step} The discount "
        "applies to every monthly bill for as long as you stay subscribed, and "
        "it is applied automatically - there is nothing to enter.\n\n"
        f"View your account: {app_url.rstrip('/')}/account\n"
        + _text_footer(
            app_url=app_url,
            unsubscribe_url=unsubscribe_url,
            postal_address=postal_address,
        )
    )
    return subject, html_body, text
