"""
Email templates. Pure functions: each returns ``(subject, html, text)`` and does
no I/O, no database reads, and no settings reads beyond the constants imported
below — so every one of them is directly testable.

NO LITERAL PERCENTAGES OR PRICES IN THIS FILE. Every number in the copy is read
from REFERRAL_PROGRAM / TIER_LIMITS in backend/models/user.py, which is the single
source of truth. A "20" typed into a template string is exactly the drift those
dicts exist to prevent: the coupon would say one thing and the email another.

HTML RULES, imposed by email clients rather than by taste:
  * Inline styles only. Gmail strips <style> blocks, so a stylesheet would leave
    the message unstyled for a large share of recipients.
  * Table-based layout, fixed 600px maximum. Outlook renders with Word's engine,
    which does not lay out modern CSS; nested tables are what it does understand.
  * Every interpolated value goes through html.escape. A display name comes from
    the user and reaches the message unfiltered otherwise.
  * The plain-text alternative is written as text, not generated by stripping
    tags. Some clients show it, and spam filters read it.
"""
from __future__ import annotations

import html
from typing import Optional

from backend.models.user import REFERRAL_PROGRAM, TIER_LIMITS

# Brand navy, matching --color-brand in frontend/src/index.css.
_BRAND = "#2a3d8f"
_INK = "#1c1f2e"
_MUTED = "#5a6072"
_PAGE_BG = "#f4f5f7"
_CARD_BG = "#ffffff"
_BORDER = "#e2e4ea"

_FONT = (
    "-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,"
    "Helvetica,Arial,sans-serif"
)

# What Rook is, in the two sentences a first email gets to spend on it.
_WHAT_ROOK_IS = (
    "Rook builds its own player valuations from raw NFL data instead of "
    "reselling someone else's projections, then gives you live bid and pick "
    "recommendations while your draft is running. It works with Yahoo, ESPN "
    "and Sleeper, in both auction and snake leagues."
)


def _esc(value: Optional[str]) -> str:
    """HTML-escape a value, quotes included, treating None as empty."""
    return html.escape(value or "", quote=True)


def _greeting_name(display_name: Optional[str]) -> str:
    """First name if we have one, else a neutral address.

    Only the first word: users type "Stephen Dubois" into the name field and
    "Hi Stephen Dubois," reads like a form letter.
    """
    name = (display_name or "").strip()
    return name.split()[0] if name else "there"


# ---------------------------------------------------------------------------
# HTML building blocks
# ---------------------------------------------------------------------------

def _paragraph(text_html: str) -> str:
    return (
        f'<p style="margin:0 0 16px 0;font-size:16px;line-height:24px;'
        f'color:{_INK};">{text_html}</p>'
    )


def _code_block(code: str, caption: str) -> str:
    """The discount or referral code, set large enough to read off a phone."""
    return (
        f'<table role="presentation" width="100%" cellpadding="0" '
        f'cellspacing="0" border="0" style="margin:0 0 20px 0;">'
        f'<tr><td align="center" style="background:{_PAGE_BG};'
        f'border:1px solid {_BORDER};border-radius:8px;padding:18px 12px;">'
        f'<div style="font-size:12px;letter-spacing:0.08em;text-transform:'
        f'uppercase;color:{_MUTED};font-family:{_FONT};margin-bottom:8px;">'
        f'{_esc(caption)}</div>'
        f'<div style="font-size:26px;font-weight:700;letter-spacing:0.12em;'
        f'color:{_INK};font-family:Menlo,Consolas,monospace;">'
        f'{_esc(code)}</div>'
        f'</td></tr></table>'
    )


def _button(href: str, label: str) -> str:
    """A bulletproof-enough CTA: a table cell with a background and a link."""
    return (
        f'<table role="presentation" cellpadding="0" cellspacing="0" '
        f'border="0" style="margin:0 0 24px 0;">'
        f'<tr><td align="center" style="background:{_BRAND};border-radius:6px;">'
        f'<a href="{_esc(href)}" style="display:inline-block;padding:13px 26px;'
        f'font-family:{_FONT};font-size:16px;font-weight:600;color:#ffffff;'
        f'text-decoration:none;">{_esc(label)}</a>'
        f'</td></tr></table>'
    )


def _promotional_footer(
    *, app_url: str, unsubscribe_url: str, postal_address: str
) -> str:
    """The CAN-SPAM footer: who sent this, where they are, how to stop it.

    The postal address and the unsubscribe link are both legally required on a
    commercial message. EmailService refuses to send a promotional template when
    the address is not configured, so an empty string here should be unreachable.
    """
    return (
        f'<tr><td style="padding:20px 32px 28px 32px;border-top:1px solid '
        f'{_BORDER};font-family:{_FONT};font-size:12px;line-height:19px;'
        f'color:{_MUTED};">'
        f'<div style="margin-bottom:8px;">'
        f'You are receiving this because you created a Rook account at '
        f'<a href="{_esc(app_url)}" style="color:{_MUTED};">{_esc(app_url)}</a>.'
        f'</div>'
        f'<div style="margin-bottom:8px;">'
        f'<a href="{_esc(unsubscribe_url)}" style="color:{_MUTED};'
        f'text-decoration:underline;">Unsubscribe from Rook emails</a>'
        f'</div>'
        f'<div>{_esc(postal_address)}</div>'
        f'</td></tr>'
    )


def _document(*, preheader: str, body_rows: str, footer_row: str) -> str:
    """Wrap body rows in the outer table shell.

    The preheader is the grey line a client shows next to the subject in the
    inbox list. Left out, it fills with whatever text comes first, which is
    usually the logo alt text.
    """
    return (
        f'<div style="background:{_PAGE_BG};margin:0;padding:0;">'
        f'<span style="display:none;font-size:1px;color:{_PAGE_BG};'
        f'max-height:0;overflow:hidden;">{_esc(preheader)}</span>'
        f'<table role="presentation" width="100%" cellpadding="0" '
        f'cellspacing="0" border="0" style="background:{_PAGE_BG};'
        f'padding:24px 0;">'
        f'<tr><td align="center" style="padding:0 12px;">'
        f'<table role="presentation" width="600" cellpadding="0" '
        f'cellspacing="0" border="0" style="width:100%;max-width:600px;'
        f'background:{_CARD_BG};border:1px solid {_BORDER};border-radius:10px;">'
        f'<tr><td style="padding:28px 32px 8px 32px;font-family:{_FONT};'
        f'font-size:20px;font-weight:700;color:{_BRAND};">Rook</td></tr>'
        f'{body_rows}'
        f'{footer_row}'
        f'</table></td></tr></table></div>'
    )


def _text_footer(*, app_url: str, unsubscribe_url: str, postal_address: str) -> str:
    return (
        "\n"
        "--\n"
        f"You are receiving this because you created a Rook account at {app_url}\n"
        f"Unsubscribe: {unsubscribe_url}\n"
        f"{postal_address}\n"
    )


